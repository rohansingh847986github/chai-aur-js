// While Loop
let i = 0;
while (i <= 10) {
  //   console.log(`Value of index is ${i}`);
  i = i + 2;
}

let arr = ["rohan", "asjbsa", "sflkjhw", "cnmcbms"];
let j = 0;
while (j < arr.length) {
  // console.log(`Value is ${arr[j]}`);
  j++;
}

// Do-While Loop
let score = 11;

do {
//   console.log(`Score is ${score}`);
  score++;
} while (score <= 10);
